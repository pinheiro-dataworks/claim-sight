"""95% bootstrap confidence intervals for every model with saved predictions.

Reads reports/predictions/validation_<model>.csv, computes percentile
intervals for accuracy @0.5, ROC-AUC and damage recall @0.5 / @0.25,
plus paired intervals for ResNet50 minus every other model, and writes
reports/confidence_intervals.{json,md}.

Usage:
    python -m src.confidence_intervals
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from src.bootstrap import (
    accuracy_at,
    bootstrap_ci,
    bootstrap_indices,
    paired_bootstrap_diff,
    recall_at,
    roc_auc,
)
from src.compare_models import DISPLAY_NAMES, REPORTS_DIR, load_all
from src.predictions import PREDICTIONS_DIR

METRICS = {
    "accuracy@0.5": accuracy_at(0.5),
    "roc_auc": roc_auc,
    "recall@0.5": recall_at(0.5),
    "recall@0.25": recall_at(0.25),
}
METRIC_LABELS = {
    "accuracy@0.5": "Accuracy @0.5",
    "roc_auc": "ROC-AUC",
    "recall@0.5": "Recall (damage) @0.5",
    "recall@0.25": "Recall (damage) @0.25",
}
REFERENCE_MODEL = "resnet50"


def compute_intervals(
    predictions_dir: Path = PREDICTIONS_DIR,
    n_resamples: int = 2000,
    confidence: float = 0.95,
    seed: int = 42,
) -> dict:
    loaded = load_all(predictions_dir)
    _, y_true, _ = next(iter(loaded.values()))
    # One shared set of resamples: every model and metric is evaluated on
    # the same bootstrap datasets, which is what makes the diffs paired.
    indices = bootstrap_indices(len(y_true), n_resamples, seed)
    kwargs = {"confidence": confidence, "indices": indices}

    result = {
        "method": "percentile bootstrap",
        "n_images": len(y_true),
        "n_resamples": n_resamples,
        "confidence": confidence,
        "seed": seed,
        "models": {
            key: {name: bootstrap_ci(y_true, p, metric, **kwargs) for name, metric in METRICS.items()}
            for key, (_, _, p) in loaded.items()
        },
        "paired_differences": {},
    }
    if REFERENCE_MODEL in loaded:
        p_ref = loaded[REFERENCE_MODEL][2]
        for key, (_, _, p_other) in loaded.items():
            if key == REFERENCE_MODEL:
                continue
            result["paired_differences"][f"{REFERENCE_MODEL}-{key}"] = {
                name: paired_bootstrap_diff(y_true, p_ref, p_other, METRICS[name], **kwargs)
                for name in ("accuracy@0.5", "roc_auc", "recall@0.5")
            }
    return result


def _fmt(ci: dict, scale: float, decimals: int, signed: bool = False, unit: str = "") -> str:
    sign = "+" if signed else ""
    point, lower, upper = (scale * ci[k] for k in ("point", "lower", "upper"))
    return f"{point:{sign}.{decimals}f}{unit} [{lower:{sign}.{decimals}f}, {upper:{sign}.{decimals}f}]"


def render_markdown(result: dict) -> str:
    pct = round(100 * result["confidence"])
    lines = [
        f"# {pct}% bootstrap confidence intervals — validation split",
        "",
        (
            f"Generated by `python -m src.confidence_intervals`: {result['method']}, "
            f"{result['n_resamples']:,} resamples of the {result['n_images']} validation images, "
            f"seed {result['seed']}. Point estimate [lower, upper]. Do not edit by hand."
        ),
        "",
        "| Model | " + " | ".join(METRIC_LABELS[m] for m in METRICS) + " |",
        "|---|" + "---|" * len(METRICS),
    ]
    for key, cis in result["models"].items():
        cells = [
            _fmt(cis[m], 1, 4) if m == "roc_auc" else _fmt(cis[m], 100, 2, unit="%")
            for m in METRICS
        ]
        lines.append(f"| {DISPLAY_NAMES[key]} | " + " | ".join(cells) + " |")

    if result["paired_differences"]:
        lines += [
            "",
            f"## Paired differences: {DISPLAY_NAMES[REFERENCE_MODEL]} minus each model",
            "",
            (
                "Computed on the same resamples, so shared image difficulty cancels out. "
                "An interval that excludes 0 indicates a difference beyond sampling noise."
            ),
            "",
            "| Compared with | Δ Accuracy @0.5 (pts) | Δ ROC-AUC | Δ Recall @0.5 (pts) |",
            "|---|---|---|---|",
        ]
        for pair, diffs in result["paired_differences"].items():
            other = pair.split("-", 1)[1]
            lines.append(
                f"| {DISPLAY_NAMES[other]} | {_fmt(diffs['accuracy@0.5'], 100, 2, True)} "
                f"| {_fmt(diffs['roc_auc'], 1, 4, True)} | {_fmt(diffs['recall@0.5'], 100, 2, True)} |"
            )
    return "\n".join(lines) + "\n"


def write_reports(result: dict, reports_dir: Path = REPORTS_DIR) -> tuple[Path, Path]:
    reports_dir.mkdir(parents=True, exist_ok=True)
    json_path = reports_dir / "confidence_intervals.json"
    md_path = reports_dir / "confidence_intervals.md"
    json_path.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8", newline="\n")
    md_path.write_text(render_markdown(result), encoding="utf-8", newline="\n")
    return json_path, md_path


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Bootstrap confidence intervals for all saved predictions.")
    parser.add_argument("--predictions-dir", type=Path, default=PREDICTIONS_DIR)
    parser.add_argument("--reports-dir", type=Path, default=REPORTS_DIR)
    parser.add_argument("--n-resamples", type=int, default=2000)
    parser.add_argument("--confidence", type=float, default=0.95)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    intervals = compute_intervals(args.predictions_dir, args.n_resamples, args.confidence, args.seed)
    for path in write_reports(intervals, args.reports_dir):
        print(f"Saved: {path}")
